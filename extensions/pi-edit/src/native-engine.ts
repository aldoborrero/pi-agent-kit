/**
 * oh-my-pi native edit engine (EditSession/EditStore) for the `edit` tool.
 *
 * Drives the Rust engine from `@oh-my-pi/pi-natives` over the SDK's tool
 * contract: the tool's native payload (path + edits[]) is serialized to the
 * engine's wire format, `EditSession` parses it, and the resulting
 * `EditWriteRequest`s are persisted by the writer below. Matching semantics
 * (exact + fuzzy with threshold) and the model-facing messages come from the
 * engine — the same battle-tested stack oh-my-pi ships in its own agent.
 *
 * Gained over the previous Pi-engine delegation:
 * - native (Rust) matching instead of JS/Pi-engine matching
 * - session-scoped snapshots + the no-op loop guard (an edit that changes
 *   nothing is rejected with a model-facing message instead of succeeding)
 * - auto-generated-file blocking (lockfiles, dist dirs, …)
 *
 * Falls back to Pi's engine delegation when the addon is unavailable —
 * callers check `hasNativeEditEngine()` first.
 */

import { existsSync } from "node:fs";
import { mkdir, rename, rm, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { homedir } from "node:os";
import { lang } from "@xynogen/pix-pretty/lang";
import { loadNatives } from "@aldoborrero/pi-natives/src/natives.ts";
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";
import { SettingsManager } from "@earendil-works/pi-coding-agent";
import { boundedDiffText, previewFromNumberedDiff } from "./preview.ts";
import type { FileDiff } from "./types.ts";

const natives = await loadNatives();

type Natives = NonNullable<Awaited<ReturnType<typeof loadNatives>>>;
type EditStore = InstanceType<Natives["EditStore"]>;
type EditSession = InstanceType<Natives["EditSession"]>;

export function hasNativeEditEngine(): boolean {
	return Boolean(natives?.EditSession && natives?.EditStore);
}

/** Model-facing rejection for auto-generated files (lockfiles, dist, …). */
export function autoGeneratedGuard(absolutePath: string, displayPath: string): string | null {
	if (!natives?.editAutoGeneratedMessage) return null;
	try {
		return natives.editAutoGeneratedMessage(absolutePath, displayPath);
	} catch {
		return null;
	}
}

// ─── Session store ──────────────────────────────────────────────────
// One store per extension instance (= one pi session; extensions are
// re-instantiated per session). Snapshots power the no-op loop guard and
// cross-call provenance; cleared on session_start.

let sharedStore: EditStore | null = null;

function getEditStore(): EditStore {
	sharedStore ??= new natives!.EditStore();
	return sharedStore;
}

export function resetEditStore(): void {
	sharedStore?.clear();
	sharedStore = null;
}

// ─── Engine policy ──────────────────────────────────────────────────
// Defaults mirror oh-my-pi's shipped settings (fuzzy match on, threshold
// 0.95, auto-generated blocking on). enforceSeenLines only gates hashline
// anchors; replace-mode edits carry line content, so provenance is not
// required. No internal-URL router in this kit: schemes are empty.

function enginePolicy(
	cwd: string,
	overrides?: Partial<import("@oh-my-pi/pi-natives").EditPolicy>,
): import("@oh-my-pi/pi-natives").EditPolicy {
	return {
		cwd,
		mode: "replace",
		allowFuzzy: true,
		fuzzyThreshold: 0.95,
		enforceSeenLines: false,
		maxColumns: 0,
		blockAutoGenerated: true,
		planActive: false,
		urlSchemes: [],
		urlAliasSchemes: [],
		planWritableRoots: [],
		homeDir: homedir(),
		rawInput: false,
		...overrides,
	};
}

// ─── Wire format ────────────────────────────────────────────────────
// The engine's replace payload is snake_case; the kit's tool params are
// camelCase. One edit serializes flat; a batch uses the internal per-file
// batch form ({path, edits[]}).

function replacePayload(
	path: string,
	edits: Array<{ oldText: string; newText: string }>,
): string {
	if (edits.length === 1) {
		return JSON.stringify({
			path,
			old_string: edits[0]!.oldText,
			new_string: edits[0]!.newText,
		});
	}
	return JSON.stringify({
		path,
		edits: edits.map((edit) => ({
			old_string: edit.oldText,
			new_string: edit.newText,
		})),
	});
}

// ─── Writer ─────────────────────────────────────────────────────────

async function persistRequest(
	pi: ExtensionAPI,
	request: import("@oh-my-pi/pi-natives").EditWriteRequest,
): Promise<import("@oh-my-pi/pi-natives").EditWriteResponse> {
	if (request.op === "delete") {
		await rm(request.path, { force: true });
		pi.events.emit("context-guard:file-modified", { path: request.path });
		return { written: "" };
	}
	if (request.content === undefined) {
		throw new Error(`Native edit ${request.op} request omitted content (${request.path})`);
	}
	if (request.op === "move") {
		if (!request.moveTo) {
			throw new Error(`Native edit move request omitted destination (${request.path})`);
		}
		await mkdir(dirname(request.moveTo), { recursive: true });
		await rename(request.path, request.moveTo).catch(async (error: unknown) => {
			// rename fails across devices/filesystems — fall back to copy+delete
			if ((error as { code?: string }).code !== "EXDEV") throw error;
			await mkdir(dirname(request.moveTo), { recursive: true });
			await writeFile(request.moveTo, request.content!, "utf-8");
			await rm(request.path, { force: true });
		});
		pi.events.emit("context-guard:file-modified", { path: request.moveTo });
		return { written: request.content };
	}
	if (request.op === "create") {
		await mkdir(dirname(request.path), { recursive: true });
	}
	await writeFile(request.path, request.content, "utf-8");
	pi.events.emit("context-guard:file-modified", { path: request.path });
	return { written: request.content };
}

/**
 * Engine selection for the native payload (`edits[]`) path.
 *
 * Default: `"pi"` — Pi's built-in engine, whose batch semantics match the
 * kit's documented contract (edits match the original content, not
 * incrementally). The oh-my-pi Rust engine applies batch edits
 * incrementally, so it stays opt-in until evaluated:
 *
 * - `PI_EDIT_ENGINE=1|true|yes` forces the native engine; any other value
 *   forces "pi"
 * - settings key `nativeEdit.enabled: true` (global + project) otherwise
 */
export function resolveEditEngine(cwd: string): "pi" | "oh-my-pi" {
	const env = process.env.PI_EDIT_ENGINE;
	if (env !== undefined) {
		return /^(1|true|yes)$/i.test(env) ? "oh-my-pi" : "pi";
	}
	try {
		const manager = SettingsManager.create(cwd);
		const read = (settings: Record<string, unknown> | undefined) =>
			(settings?.nativeEdit as { enabled?: unknown } | undefined)?.enabled;
		return read(manager.getProjectSettings() as Record<string, unknown>) === true ||
			read(manager.getGlobalSettings() as Record<string, unknown>) === true
			? "oh-my-pi"
			: "pi";
	} catch {
		return "pi";
	}
}

// ─── Engine run ─────────────────────────────────────────────────────────

export interface NativeEditPlan {
	path: string;
	edits: Array<{ oldText: string; newText: string }>;
}

export interface NativeEditSuccess {
	ok: true;
	text: string;
	/** Bounded combined diff of every file the engine touched. */
	diff: string;
	firstChangedLine?: number;
	fileChanges: FileDiff[];
}

export interface NativeEditFailure {
	ok: false;
	/** Model-facing message from the engine (match failure, guard, no-op, …). */
	text: string;
}

export type NativeEditResult = NativeEditSuccess | NativeEditFailure;

/**
 * Run the plan through the native engine. Single entry point for the
 * `edit` tool's native payload; never throws for engine failures — those
 * come back as `NativeEditFailure` with the engine's model-facing text.
 * I/O errors in the writer still throw (they are host-side, not engine-side).
 */
export async function executeOhMyPiEdits(
	pi: ExtensionAPI,
	plan: NativeEditPlan,
	cwd: string,
): Promise<NativeEditResult> {
	const absolutePath = plan.path.startsWith("/") ? plan.path : `${cwd}/${plan.path}`;

	// Pre-flight guard: clearer rejection before the engine stages anything.
	const guard = autoGeneratedGuard(absolutePath, plan.path);
	if (guard) return { ok: false, text: guard };

	const session: EditSession = new natives!.EditSession(
		getEditStore(),
		enginePolicy(cwd),
	);

	try {
		session.setArgsJson(replacePayload(plan.path, plan.edits));
		session.finish();
		const outcome = await session.apply({ lspFlush: false }, (error, request) =>
			error ? Promise.reject(error) : persistRequest(pi, request),
		);

		if (outcome.isError) {
			return { ok: false, text: outcome.text || "Edit failed." };
		}

		const firstChangedLine = outcome.files.find(
			(file) => file.firstChangedLine !== undefined,
		)?.firstChangedLine;
		const fileChanges: FileDiff[] = outcome.files.map((file) => ({
			format: "hunks-v1" as const,
			path: file.path,
			language: lang(file.path),
			firstChangedLine: file.firstChangedLine,
			preview: previewFromNumberedDiff(file.diff),
		}));
		const rawDiff = outcome.files
			.map((file) => file.diff)
			.filter((diff) => diff.length > 0)
			.join("\n");

		const perFile = outcome.files.map((file, index) => `${index + 1}. ${file.text}`).join("\n");
		return {
			ok: true,
			text: perFile || outcome.text,
			diff: boundedDiffText(rawDiff),
			firstChangedLine,
			fileChanges,
		};
	} finally {
		session.close();
	}
}

/**
 * Run a hashline payload (`{input}` DSL: `[path#TAG]` headers + `PUT`/`CUT`/
 * `REM`/`MV` hunks) through the native engine. Anchors are validated against
 * snapshots recorded by the `read` wrapper — never-read files are rejected
 * with a model-facing message telling the model to read first.
 */
export async function executeOhMyPiHashline(
	pi: ExtensionAPI,
	plan: { input: string },
	cwd: string,
): Promise<NativeEditResult> {
	const session: EditSession = new natives!.EditSession(
		getEditStore(),
		enginePolicy(cwd, { mode: "hashline", enforceSeenLines: true }),
	);
	try {
		session.setArgsJson(JSON.stringify({ input: plan.input }));
		session.finish();
		const outcome = await session.apply({ lspFlush: false }, (error, request) =>
			error ? Promise.reject(error) : persistRequest(pi, request),
		);
		if (outcome.isError) return { ok: false, text: outcome.text || "Edit failed." };
		const firstChangedLine = outcome.files.find(
			(file) => file.firstChangedLine !== undefined,
		)?.firstChangedLine;
		const fileChanges: FileDiff[] = outcome.files.map((file) => ({
			format: "hunks-v1" as const,
			path: file.path,
			language: lang(file.path),
			firstChangedLine: file.firstChangedLine,
			preview: previewFromNumberedDiff(file.diff),
		}));
		const rawDiff = outcome.files
			.map((file) => file.diff)
			.filter((diff) => diff.length > 0)
			.join("\n");
		const perFile = outcome.files.map((file, index) => `${index + 1}. ${file.text}`).join("\n");
		return {
			ok: true,
			text: perFile || outcome.text,
			diff: boundedDiffText(rawDiff),
			firstChangedLine,
			fileChanges,
		};
	} finally {
		session.close();
	}
}

/**
 * Record a snapshot tag for `absolutePath` on behalf of the `read` wrapper.
 * The tag (`[displayPath#TAG]` in read output) is what hashline payloads
 * anchor on; the engine validates it against this store at apply time.
 * Returns the 4-hex tag, or null when the addon is unavailable or the file
 * is unreadable/larger than the store's limit.
 */
export function hashlineSnapshotTag(absolutePath: string): string | null {
	if (!natives?.EditStore) return null;
	try {
		return getEditStore().recordSnapshotFile(absolutePath);
	} catch {
		return null;
	}
}

/**
 * Hashline gate: whether the `hashline` edit param and the tag-emitting
 * `read` wrapper are offered. Default off — hashline changes the read tool
 * output, so it ships opt-in like the native engine:
 *
 * - `PI_EDIT_HASHLINE=1|true|yes` forces on; any other value forces off
 * - settings key `nativeEdit.hashline: true` (global + project) otherwise
 */
export function resolveHashlineEnabled(cwd: string): boolean {
	const env = process.env.PI_EDIT_HASHLINE;
	if (env !== undefined) return /^(1|true|yes)$/i.test(env);
	try {
		const manager = SettingsManager.create(cwd);
		const read = (settings: Record<string, unknown> | undefined) =>
			(settings?.nativeEdit as { hashline?: unknown } | undefined)?.hashline;
		return read(manager.getProjectSettings() as Record<string, unknown>) === true ||
			read(manager.getGlobalSettings() as Record<string, unknown>) === true;
	} catch {
		return false;
	}
}

// ─── astEdit: semantic rewrites (ast-grep) ──────────────────────────

export interface AstEditPlan {
	/** Rewrite rules: ast-grep pattern → replacement template. */
	rewrites: Array<{ pattern: string; rewrite: string }>;
	/** Scan root; defaults to cwd. */
	path?: string;
	/** Glob filter within the scan root. */
	glob?: string;
	/** Language override; native infers per file when omitted. */
	lang?: string;
	/** When true, write to disk after the dry-run guard passes. */
	apply?: boolean;
}

const AST_MAX_REPLACEMENTS = 500;
const AST_MAX_FILES = 100;

/**
 * The engine reports touched paths relative to the scan input spelling.
 * Resolve against cwd first, then against the scan root's directory, so the
 * auto-generated guard opens the real file.
 */
function resolveReportedPath(reported: string, cwd: string, scanRoot: string): string {
	if (reported.startsWith("/")) return reported;
	const fromCwd = `${cwd}/${reported}`;
	if (existsSync(fromCwd)) return fromCwd;
	const fromRootDir = `${scanRoot.split("/").slice(0, -1).join("/")}/${reported}`;
	if (existsSync(fromRootDir)) return fromRootDir;
	return fromCwd;
}

function astScanRoot(plan: AstEditPlan, cwd: string): string {
	if (!plan.path) return cwd;
	return plan.path.startsWith("/") ? plan.path : `${cwd}/${plan.path}`;
}

/**
 * Semantic rewrites through the native astEdit engine. Always runs a dry
 * run first: auto-generated targets (codegen patterns) abort the operation
 * before anything touches disk. Without `apply`, the caller gets the full
 * per-change preview; with `apply`, a second pass writes to disk.
 *
 * Never throws for engine-level outcomes (no matches, parse errors) — those
 * come back in the result; host I/O failures throw.
 */
export async function executeAstEdit(
	plan: AstEditPlan,
	cwd: string,
): Promise<NativeEditResult & { details?: import("@oh-my-pi/pi-natives").AstReplaceResult }> {
	if (!natives?.astEdit) return { ok: false, text: "Semantic edit requires @oh-my-pi/pi-natives." };

	const rewrites: Record<string, string> = {};
	for (const rule of plan.rewrites) rewrites[rule.pattern] = rule.rewrite;

	const run = (dryRun: boolean) =>
		natives!.astEdit({
			rewrites,
			path: astScanRoot(plan, cwd),
			...(plan.glob ? { glob: plan.glob } : {}),
			...(plan.lang ? { lang: plan.lang } : {}),
			dryRun,
			maxReplacements: AST_MAX_REPLACEMENTS,
			maxFiles: AST_MAX_FILES,
		});

	// Pass 1: dry run — what would change, on which files.
	const preview = await run(true);
	const scanRoot = astScanRoot(plan, cwd);

	// Guard: codegen outputs must not be rewritten (same policy as edits).
	// The engine reports paths relative to the scan input; resolve them
	// before handing them to the guard (it opens the file).
	for (const file of preview.fileChanges) {
		const candidate = resolveReportedPath(file.path, cwd, scanRoot);
		const guard = autoGeneratedGuard(candidate, file.path);
		if (guard) return { ok: false, text: guard };
	}

	if (preview.totalReplacements === 0) {
		const problems = preview.parseErrors?.length
			? ` Parse errors: ${preview.parseErrors.join(" | ")}`
			: "";
		return {
			ok: false,
			text: `No matches for the ${plan.rewrites.length} rewrite rule(s).${problems}`,
		};
	}

	// Pass 2: apply when requested (re-runs the rewrite for real).
	const result = plan.apply ? await run(false) : preview;

	const firstChange = result.changes[0];
	const fileChanges: FileDiff[] = result.fileChanges.map((file) => {
		// Rebuild the numbered diff for this file from its changes, ordered
		// by byte offset, in the engine's line-numbered format.
		const changes = result.changes
			.filter((change) => change.path === file.path)
			.sort((a, b) => a.byteStart - b.byteStart);
		const body = changes
			.map((change) => {
				const oldLines = change.before.split("\n").map((line, index) => `-${change.startLine + index}|${line}`);
				const newLines = change.after.split("\n").map((line, index) => `+${change.startLine + index}|${line}`);
				return [...oldLines, ...newLines].join("\n");
			})
			.join("\n");
		return {
			format: "hunks-v1" as const,
			path: file.path,
			language: lang(file.path),
			firstChangedLine: changes[0]?.startLine,
			preview: previewFromNumberedDiff(body),
		};
	});
	const rawDiff = result.changes
		.map((change) => {
			const oldLines = change.before.split("\n").map((line, index) => `-${change.startLine + index}|${line}`);
			const newLines = change.after.split("\n").map((line, index) => `+${change.startLine + index}|${line}`);
			return [...oldLines, ...newLines].join("\n");
		})
		.join("\n");

	const mode = result.applied ? "Applied" : "Previewed";
	const perFile = result.fileChanges
		.map((file, index) => `${index + 1}. ${file.path}: ${file.count} replacement(s)`)
		.join("\n");
	const summary =
		`${mode} ${result.totalReplacements} replacement(s) across ${result.filesTouched} file(s).` +
		(result.limitReached ? " (limit reached — refine the rules or scope.)" : "") +
		(perFile ? `\n${perFile}` : "");

	return {
		ok: true,
		text: summary,
		diff: boundedDiffText(rawDiff),
		firstChangedLine: firstChange?.startLine,
		fileChanges,
		details: result,
	};
}
