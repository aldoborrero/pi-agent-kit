/**
 * oh-my-pi native edit engine (EditSession/EditStore) for the `edit` tool.
 *
 * Drives the Rust engine from `@oh-my-pi/pi-natives` over the SDK's tool
 * contract: the tool's native payload (path + edits[]) is serialized to the
 * engine's wire format, `EditSession` parses it, and the resulting
 * `EditWriteRequest`s are persisted by the writer below. Matching semantics
 * (exact + fuzzy with threshold) and the model-facing messages come from the
 * engine — the same battle-tested stack oh-my-pi ships in its own agent.
 *
 * Gained over the previous Pi-engine delegation:
 * - native (Rust) matching instead of JS/Pi-engine matching
 * - session-scoped snapshots + the no-op loop guard (an edit that changes
 *   nothing is rejected with a model-facing message instead of succeeding)
 * - auto-generated-file blocking (lockfiles, dist dirs, …)
 *
 * Falls back to Pi's engine delegation when the addon is unavailable —
 * callers check `hasNativeEditEngine()` first.
 */

import { mkdir, rename, rm, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { homedir } from "node:os";
import { lang } from "@xynogen/pix-pretty/lang";
import { loadNatives } from "@aldoborrero/pi-natives/src/natives.ts";
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";
import { SettingsManager } from "@earendil-works/pi-coding-agent";
import { boundedDiffText, previewFromNumberedDiff } from "./preview.ts";
import type { FileDiff } from "./types.ts";

const natives = await loadNatives();

type Natives = NonNullable<Awaited<ReturnType<typeof loadNatives>>>;
type EditStore = InstanceType<Natives["EditStore"]>;
type EditSession = InstanceType<Natives["EditSession"]>;

export function hasNativeEditEngine(): boolean {
	return Boolean(natives?.EditSession && natives?.EditStore);
}

/** Model-facing rejection for auto-generated files (lockfiles, dist, …). */
export function autoGeneratedGuard(absolutePath: string, displayPath: string): string | null {
	if (!natives?.editAutoGeneratedMessage) return null;
	try {
		return natives.editAutoGeneratedMessage(absolutePath, displayPath);
	} catch {
		return null;
	}
}

// ─── Session store ──────────────────────────────────────────────────
// One store per extension instance (= one pi session; extensions are
// re-instantiated per session). Snapshots power the no-op loop guard and
// cross-call provenance; cleared on session_start.

let sharedStore: EditStore | null = null;

function getEditStore(): EditStore {
	sharedStore ??= new natives!.EditStore();
	return sharedStore;
}

export function resetEditStore(): void {
	sharedStore?.clear();
	sharedStore = null;
}

// ─── Engine policy ──────────────────────────────────────────────────
// Defaults mirror oh-my-pi's shipped settings (fuzzy match on, threshold
// 0.95, auto-generated blocking on). enforceSeenLines only gates hashline
// anchors; replace-mode edits carry line content, so provenance is not
// required. No internal-URL router in this kit: schemes are empty.

function enginePolicy(cwd: string): import("@oh-my-pi/pi-natives").EditPolicy {
	return {
		cwd,
		mode: "replace",
		allowFuzzy: true,
		fuzzyThreshold: 0.95,
		enforceSeenLines: false,
		maxColumns: 0,
		blockAutoGenerated: true,
		planActive: false,
		urlSchemes: [],
		urlAliasSchemes: [],
		planWritableRoots: [],
		homeDir: homedir(),
		rawInput: false,
	};
}

// ─── Wire format ────────────────────────────────────────────────────
// The engine's replace payload is snake_case; the kit's tool params are
// camelCase. One edit serializes flat; a batch uses the internal per-file
// batch form ({path, edits[]}).

function replacePayload(
	path: string,
	edits: Array<{ oldText: string; newText: string }>,
): string {
	if (edits.length === 1) {
		return JSON.stringify({
			path,
			old_string: edits[0]!.oldText,
			new_string: edits[0]!.newText,
		});
	}
	return JSON.stringify({
		path,
		edits: edits.map((edit) => ({
			old_string: edit.oldText,
			new_string: edit.newText,
		})),
	});
}

// ─── Writer ─────────────────────────────────────────────────────────

async function persistRequest(
	pi: ExtensionAPI,
	request: import("@oh-my-pi/pi-natives").EditWriteRequest,
): Promise<import("@oh-my-pi/pi-natives").EditWriteResponse> {
	if (request.op === "delete") {
		await rm(request.path, { force: true });
		pi.events.emit("context-guard:file-modified", { path: request.path });
		return { written: "" };
	}
	if (request.content === undefined) {
		throw new Error(`Native edit ${request.op} request omitted content (${request.path})`);
	}
	if (request.op === "move") {
		if (!request.moveTo) {
			throw new Error(`Native edit move request omitted destination (${request.path})`);
		}
		await mkdir(dirname(request.moveTo), { recursive: true });
		await rename(request.path, request.moveTo).catch(async (error: unknown) => {
			// rename fails across devices/filesystems — fall back to copy+delete
			if ((error as { code?: string }).code !== "EXDEV") throw error;
			await mkdir(dirname(request.moveTo), { recursive: true });
			await writeFile(request.moveTo, request.content!, "utf-8");
			await rm(request.path, { force: true });
		});
		pi.events.emit("context-guard:file-modified", { path: request.moveTo });
		return { written: request.content };
	}
	if (request.op === "create") {
		await mkdir(dirname(request.path), { recursive: true });
	}
	await writeFile(request.path, request.content, "utf-8");
	pi.events.emit("context-guard:file-modified", { path: request.path });
	return { written: request.content };
}

/**
 * Engine selection for the native payload (`edits[]`) path.
 *
 * Default: `"pi"` — Pi's built-in engine, whose batch semantics match the
 * kit's documented contract (edits match the original content, not
 * incrementally). The oh-my-pi Rust engine applies batch edits
 * incrementally, so it stays opt-in until evaluated:
 *
 * - `PI_EDIT_ENGINE=1|true|yes` forces the native engine; any other value
 *   forces "pi"
 * - settings key `nativeEdit.enabled: true` (global + project) otherwise
 */
export function resolveEditEngine(cwd: string): "pi" | "oh-my-pi" {
	const env = process.env.PI_EDIT_ENGINE;
	if (env !== undefined) {
		return /^(1|true|yes)$/i.test(env) ? "oh-my-pi" : "pi";
	}
	try {
		const manager = SettingsManager.create(cwd);
		const read = (settings: Record<string, unknown> | undefined) =>
			(settings?.nativeEdit as { enabled?: unknown } | undefined)?.enabled;
		return read(manager.getProjectSettings() as Record<string, unknown>) === true ||
			read(manager.getGlobalSettings() as Record<string, unknown>) === true
			? "oh-my-pi"
			: "pi";
	} catch {
		return "pi";
	}
}

// ─── Engine run ─────────────────────────────────────────────────────────

export interface NativeEditPlan {
	path: string;
	edits: Array<{ oldText: string; newText: string }>;
}

export interface NativeEditSuccess {
	ok: true;
	text: string;
	/** Bounded combined diff of every file the engine touched. */
	diff: string;
	firstChangedLine?: number;
	fileChanges: FileDiff[];
}

export interface NativeEditFailure {
	ok: false;
	/** Model-facing message from the engine (match failure, guard, no-op, …). */
	text: string;
}

export type NativeEditResult = NativeEditSuccess | NativeEditFailure;

/**
 * Run the plan through the native engine. Single entry point for the
 * `edit` tool's native payload; never throws for engine failures — those
 * come back as `NativeEditFailure` with the engine's model-facing text.
 * I/O errors in the writer still throw (they are host-side, not engine-side).
 */
export async function executeOhMyPiEdits(
	pi: ExtensionAPI,
	plan: NativeEditPlan,
	cwd: string,
): Promise<NativeEditResult> {
	const absolutePath = plan.path.startsWith("/") ? plan.path : `${cwd}/${plan.path}`;

	// Pre-flight guard: clearer rejection before the engine stages anything.
	const guard = autoGeneratedGuard(absolutePath, plan.path);
	if (guard) return { ok: false, text: guard };

	const session: EditSession = new natives!.EditSession(
		getEditStore(),
		enginePolicy(cwd),
	);

	try {
		session.setArgsJson(replacePayload(plan.path, plan.edits));
		session.finish();
		const outcome = await session.apply({ lspFlush: false }, (error, request) =>
			error ? Promise.reject(error) : persistRequest(pi, request),
		);

		if (outcome.isError) {
			return { ok: false, text: outcome.text || "Edit failed." };
		}

		const firstChangedLine = outcome.files.find(
			(file) => file.firstChangedLine !== undefined,
		)?.firstChangedLine;
		const fileChanges: FileDiff[] = outcome.files.map((file) => ({
			format: "hunks-v1" as const,
			path: file.path,
			language: lang(file.path),
			firstChangedLine: file.firstChangedLine,
			preview: previewFromNumberedDiff(file.diff),
		}));
		const rawDiff = outcome.files
			.map((file) => file.diff)
			.filter((diff) => diff.length > 0)
			.join("\n");

		const perFile = outcome.files.map((file, index) => `${index + 1}. ${file.text}`).join("\n");
		return {
			ok: true,
			text: perFile || outcome.text,
			diff: boundedDiffText(rawDiff),
			firstChangedLine,
			fileChanges,
		};
	} finally {
		session.close();
	}
}
