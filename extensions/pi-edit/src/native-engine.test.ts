import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { executeOhMyPiEdits, hasNativeEditEngine, resetEditStore } from "./native-engine.ts";

const d = hasNativeEditEngine() ? describe : describe.skip;

const mockPi = {
	events: { emit: () => {} },
} as unknown as Parameters<typeof executeOhMyPiEdits>[0];

let workDir: string;

beforeAll(() => {
	workDir = mkdtempSync(join(tmpdir(), "pi-edit-native-"));
});

afterAll(() => {
	resetEditStore();
	rmSync(workDir, { recursive: true, force: true });
});

function write(path: string, content: string): string {
	const absolute = join(workDir, path);
	writeFileSync(absolute, content, "utf-8");
	return absolute;
}

function run(path: string, edits: Array<{ oldText: string; newText: string }>) {
	return executeOhMyPiEdits(mockPi, { path, edits }, workDir);
}

d("executeOhMyPiEdits (native EditSession engine)", () => {
	test("exact single replacement persists to disk", async () => {
		write("a.ts", "alpha\nbeta\ngamma\n");
		const result = await run("a.ts", [{ oldText: "beta", newText: "BETA" }]);
		expect(result.ok).toBe(true);
		expect(readFileSync(join(workDir, "a.ts"), "utf-8")).toBe("alpha\nBETA\ngamma\n");
		if (result.ok) {
			expect(result.diff).toContain("BETA");
			expect(result.fileChanges[0]!.path).toBe(join(workDir, "a.ts"));
			expect(result.fileChanges[0]!.format).toBe("hunks-v1");
			expect(result.fileChanges[0]!.preview.added).toBe(1);
			expect(result.fileChanges[0]!.preview.removed).toBe(1);
		}
	});

	test("batch edits in one file (per-file batch form)", async () => {
		write("b.ts", "one\ntwo\nthree\n");
		const result = await run("b.ts", [
			{ oldText: "one", newText: "1" },
			{ oldText: "three", newText: "3" },
		]);
		expect(result.ok).toBe(true);
		expect(readFileSync(join(workDir, "b.ts"), "utf-8")).toBe("1\ntwo\n3\n");
	});

	test("fuzzy match applies with default threshold (small typo)", async () => {
		write("c.ts", "export function computeTotals(items) {\n  return items.length;\n}\n");
		// one character drift: 'computeTotals' -> 'computTotals'
		const result = await run("c.ts", [{ oldText: "export function computTotals(items) {", newText: "export function computeTotals(items: unknown[]) {" }]);
		expect(result.ok).toBe(true);
		expect(readFileSync(join(workDir, "c.ts"), "utf-8")).toContain("(items: unknown[])");
	});

	test("no match -> model-facing failure, file untouched", async () => {
		const original = "stable content\n";
		write("d.ts", original);
		const result = await run("d.ts", [{ oldText: "does not exist anywhere", newText: "x" }]);
		expect(result.ok).toBe(false);
		if (!result.ok) {
			expect(result.text.length).toBeGreaterThan(0);
		}
		expect(readFileSync(join(workDir, "d.ts"), "utf-8")).toBe(original);
	});

	test("no-op edit (oldText == newText) is rejected by the loop guard", async () => {
		write("e.ts", "loop-target\n");
		const first = await run("e.ts", [{ oldText: "loop-target", newText: "loop-target" }]);
		expect(first.ok).toBe(false);
		if (!first.ok) {
			expect(first.text.toLowerCase()).toContain("no");
		}
	});

	test("auto-generated file is blocked with a model-facing guard", async () => {
		// The engine's detector targets codegen outputs: _pb2.py, @generated
		// markers, zz_generated.*, .gen.* — not lockfiles.
		write("user_pb2.py", "# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\ncontent = 1\n");
		const result = await run("user_pb2.py", [{ oldText: "content = 1", newText: "content = 2" }]);
		expect(result.ok).toBe(false);
		if (!result.ok) {
			expect(result.text).toContain("user_pb2.py");
			expect(result.text).toContain("auto-generated");
		}
	});

	test("snapshots persist across calls (cross-call store)", async () => {
		write("f.ts", "first\n");
		await run("f.ts", [{ oldText: "first", newText: "second" }]);
		const result = await run("f.ts", [{ oldText: "second", newText: "third" }]);
		expect(result.ok).toBe(true);
		expect(readFileSync(join(workDir, "f.ts"), "utf-8")).toBe("third\n");
	});

	test("resetEditStore clears snapshots (fresh session)", async () => {
		write("g.ts", "value-a\n");
		await run("g.ts", [{ oldText: "value-a", newText: "value-b" }]);
		resetEditStore();
		const result = await run("g.ts", [{ oldText: "value-b", newText: "value-c" }]);
		expect(result.ok).toBe(true);
		expect(readFileSync(join(workDir, "g.ts"), "utf-8")).toBe("value-c\n");
	});
});