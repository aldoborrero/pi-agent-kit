import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { executeAstEdit, hasNativeEditEngine, resetEditStore, autoGeneratedGuard } from "./native-engine.ts";

const d = hasNativeEditEngine() ? describe : describe.skip;

let workDir: string;

beforeAll(() => {
	workDir = mkdtempSync(join(tmpdir(), "pi-edit-ast-"));
});

afterAll(() => {
	resetEditStore();
	rmSync(workDir, { recursive: true, force: true });
});

function write(path: string, content: string): string {
	const absolute = join(workDir, path);
	mkdirSync(join(absolute, ".."), { recursive: true });
	writeFileSync(absolute, content, "utf-8");
	return absolute;
}

function run(
	rewrites: Array<{ pattern: string; rewrite: string }>,
	options?: { path?: string; glob?: string; apply?: boolean },
) {
	return executeAstEdit({ rewrites, ...options }, workDir);
}

d("executeAstEdit (semantic rewrites via astEdit)", () => {
	test("dry-run preview: matches found, file untouched", async () => {
		const original = 'console.log("a");\nconsole.log("b");\n';
		write("dry.ts", original);
		const result = await run([{ pattern: 'console.log($A)', rewrite: "$A" }]);
		expect(result.ok).toBe(true);
		expect(readFileSync(join(workDir, "dry.ts"), "utf-8")).toBe(original);
		if (result.ok) {
			expect(result.text).toContain("Previewed 2 replacement");
			expect(result.diff).toContain("console.log");
			expect(result.fileChanges[0]!.preview.added).toBe(2);
			expect(result.fileChanges[0]!.preview.removed).toBe(2);
		}
	});

	test("apply writes to disk and reports counts", async () => {
		write("apply.ts", 'console.log("x");\nconst y = console.log("y");\n');
		const result = await run(
			[{ pattern: "console.log($A)", rewrite: "logger($A)" }],
			{ path: "apply.ts", apply: true },
		);
		expect(result.ok).toBe(true);
		const after = readFileSync(join(workDir, "apply.ts"), "utf-8");
		expect(after).toContain('logger("x")');
		expect(after).toContain('logger("y")');
		expect(after).not.toContain("console.log");
		if (result.ok) expect(result.text).toContain("Applied 2 replacement");
	});

	test("metavariables flow through to the rewrite", async () => {
		write("meta.ts", "const total = sum(a, b);\n");
		const result = await run(
			[{ pattern: "sum($A, $B)", rewrite: "$A + $B" }],
			{ path: "meta.ts", apply: true },
		);
		expect(result.ok).toBe(true);
		expect(readFileSync(join(workDir, "meta.ts"), "utf-8")).toContain("const total = a + b;");
	});

	test("glob scopes the rewrite to matching files", async () => {
		write("scoped/a.ts", 'console.log("one");\n');
		write("scoped/b.txt", "console.log(not code)\n");
		const result = await run(
			[{ pattern: "console.log($A)", rewrite: "$A" }],
			{ path: "scoped", glob: "*.ts", apply: true },
		);
		expect(result.ok).toBe(true);
		expect(readFileSync(join(workDir, "scoped/a.ts"), "utf-8")).toContain("one");
		expect(readFileSync(join(workDir, "scoped/b.txt"), "utf-8")).toContain("console.log");
	});

	test("auto-generated target is blocked before applying", async () => {
		write("user_pb2.py", '# Generated by the protocol buffer compiler.  DO NOT EDIT!\nx = console.log("a");\n');
		const result = await run(
			[{ pattern: "console.log($A)", rewrite: "$A" }],
			{ path: "user_pb2.py", apply: true },
		);
		expect(result.ok).toBe(false);
		if (!result.ok) expect(result.text).toContain("auto-generated");
		// File untouched.
		expect(readFileSync(join(workDir, "user_pb2.py"), "utf-8")).toContain("console.log");
	});

	test("no matches -> model-facing failure with rule count", async () => {
		write("nomatch.ts", "const plain = 1;\n");
		const result = await run([{ pattern: "awaitNotHere($X)", rewrite: "$X" }], { path: "nomatch.ts" });
		expect(result.ok).toBe(false);
		if (!result.ok) expect(result.text).toContain("No matches for the 1 rewrite rule");
	});

	test("limitReached is surfaced when capped", async () => {
		const many = Array.from({ length: 30 }, (_, i) => `console.log(${i});`).join("\n");
		write("many.ts", `${many}\n`);
		const result = await run(
			[{ pattern: "console.log($A)", rewrite: "$A" }],
			{ path: "many.ts", apply: true },
		);
		// Default cap (500) not reached by 30 matches — limitReached must be false.
		expect(result.ok).toBe(true);
		if (result.ok) expect(result.text).not.toContain("limit reached");
	});
});